fun AppStrings.platformLabel(p: com.vythera.vyxelapps.AppPlatform): String = when (p) {
    com.vythera.vyxelapps.AppPlatform.ALL     -> allPlatforms
    com.vythera.vyxelapps.AppPlatform.ANDROID -> "Android"
    com.vythera.vyxelapps.AppPlatform.WINDOWS -> "Windows"
    com.vythera.vyxelapps.AppPlatform.LINUX   -> "Linux"
    com.vythera.vyxelapps.AppPlatform.TV      -> "TV"
    com.vythera.vyxelapps.AppPlatform.IOS     -> "iOS"
}

