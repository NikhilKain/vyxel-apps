/**
 * Integrity-card copy, deliberately NOT part of [AppStrings].
 *
 * AppStrings' generated constructor sits at Dalvik's 255-argument ceiling for
 * `invoke-range`: adding ~10 more fields makes the whole AppStringsKt class fail
 * verification at load time (`VerifyError: invalid arg count (0) in range
 * invoke`) and the app dies on first composition. Any *new* group of strings
 * needs its own holder like this one until these move to string resources.
 */
/**
 * Cyberpunk-only chrome copy. Same reason as [IntegrityStrings]: AppStrings
 * cannot take another field without failing dex verification.
 */
data class CyberStrings(
    val readyToExplore : String = "Ready to explore?",
    val viewAll        : String = "View all"
)

val LocalCyberStrings = compositionLocalOf { CyberStrings() }

